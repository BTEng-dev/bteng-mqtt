"""Sniff a broker and propose a topic registry.

MQTT has no information model. OPC UA's ``harvest`` reads types from the server
and is authoritative; this **is not**: it listens to live traffic for a while and
*guesses* from what it sees. A topic that stayed quiet is invisible, and a
counter that only ever sent ``0`` looks like an int even if it is a float. The
generated file says so in its header, and a human is expected to read it.

The inference itself (:func:`infer_definitions`) is a pure function of the
observed payloads, so it is fully testable without a broker; :func:`sniff` is the
thin I/O layer that collects them.
"""
from __future__ import annotations

import json
import logging
import re
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from bteng_mqtt.client import MqttClientManager
from bteng_mqtt.registry import BrokerConfig
from bteng_mqtt.topics import is_wildcard, topic_matches, validate_filter
from bteng_mqtt.types import MqttPayloadType

logger = logging.getLogger(__name__)

DISCOVER_CLIENT_ID = "bteng-mqtt-discover"

_BOOL_WORDS = frozenset({"true", "false", "on", "off", "yes", "no"})
_NOT_IDENTIFIER = re.compile(r"[^0-9a-zA-Z]+")
_CAMEL_BOUNDARY = re.compile(r"(?<=[a-z0-9])(?=[A-Z])")

HEADER = """\
# Generated by `bteng-mqtt discover` from {source}.
#
# MQTT has no information model, so these payload types are INFERRED from
# {samples} message(s) seen over {duration:.0f}s — they are a starting point, not
# a source of truth. Review them: a topic that was quiet during the sniff is
# missing entirely, and a field that only ever carried whole numbers is typed
# 'int' even when it is really a float.
#
# Re-run the command to refresh. Sections other than `topics:` are preserved, and
# so is any topic marked `manual: true` — use that for the entries a sniff can
# never produce (wildcards, request/response pairs, value_maps).
"""


# ── Spec ──────────────────────────────────────────────────────────────────────

@dataclass
class DiscoverSpec:
    """What to sniff, and for how long — the hand-written half of discovery."""
    broker:   BrokerConfig = field(default_factory=BrokerConfig)
    filters:  list[str] = field(default_factory=lambda: ["#"])
    duration: float = 15.0
    qos:      int = 0
    #: topic → alias, to pin names the derivation would not guess
    aliases:  dict[str, str] = field(default_factory=dict)
    #: filters whose topics are dropped from the result (e.g. "$SYS/#")
    exclude:  list[str] = field(default_factory=list)

    @classmethod
    def from_dict(cls, data: dict | None) -> DiscoverSpec:
        data = data or {}
        raw_filters = data.get("filters") or data.get("discover") or ["#"]
        if isinstance(raw_filters, str):
            raw_filters = [raw_filters]
        filters = [str(f) for f in raw_filters]
        for topic_filter in filters:
            validate_filter(topic_filter)
        exclude = [str(f) for f in (data.get("exclude") or [])]
        for topic_filter in exclude:
            validate_filter(topic_filter)
        qos = int(data.get("qos", 0))
        if qos not in (0, 1, 2):
            raise ValueError(f"discover qos must be 0, 1 or 2, got {qos}")
        return cls(
            broker=BrokerConfig.from_dict(data.get("broker")),
            filters=filters,
            duration=float(data.get("duration", 15.0)),
            qos=qos,
            aliases={str(k): str(v) for k, v in (data.get("aliases") or {}).items()},
            exclude=exclude,
        )

    @classmethod
    def from_file(cls, path: str | Path) -> DiscoverSpec:
        text = Path(path).read_text(encoding="utf-8")
        return cls.from_dict(yaml.safe_load(text) or {})


# ── Inference (pure) ──────────────────────────────────────────────────────────

def _decode_text(payload: bytes) -> str | None:
    try:
        return payload.decode("utf-8")
    except UnicodeDecodeError:
        return None


def _looks_int(text: str) -> bool:
    try:
        int(text.strip())
    except ValueError:
        return False
    return True


def _looks_float(text: str) -> bool:
    try:
        float(text.strip())
    except ValueError:
        return False
    return True


def _json_value(text: str) -> Any:
    """Parsed JSON if the payload is a JSON object or array, else None.

    A bare ``42`` is valid JSON but is better described as an int, so only
    containers count as ``json`` here.
    """
    try:
        value = json.loads(text)
    except (json.JSONDecodeError, ValueError):
        return None
    return value if isinstance(value, (dict, list)) else None


def infer_payload_type(payloads: list[bytes]) -> tuple[MqttPayloadType, list[str]]:
    """Infer a payload type from every sample seen on one topic.

    Returns the type and the JSON keys observed (empty for non-json topics).
    Deliberately conservative: one sample that does not fit a narrow type widens
    the guess rather than dropping the sample.
    """
    texts: list[str] = []
    for payload in payloads:
        text = _decode_text(payload)
        if text is None:
            return MqttPayloadType.BYTES, []
        texts.append(text)

    if not texts:
        return MqttPayloadType.STRING, []

    json_values = [_json_value(text) for text in texts]
    if all(value is not None for value in json_values):
        keys: list[str] = []
        for value in json_values:
            if isinstance(value, dict):
                keys.extend(k for k in value if k not in keys)
        return MqttPayloadType.JSON, keys

    stripped = [text.strip().lower() for text in texts]
    # A word like "true" is unambiguous; 0/1 is not, and int wins there because
    # a counter is more common than a flag that never says "true".
    if all(word in _BOOL_WORDS for word in stripped):
        return MqttPayloadType.BOOL, []
    if all(_looks_int(text) for text in texts):
        return MqttPayloadType.INT, []
    if all(_looks_float(text) for text in texts):
        return MqttPayloadType.FLOAT, []
    return MqttPayloadType.STRING, []


def snake_case(text: str) -> str:
    """``TestBool`` → ``test_bool``; ``robot-state`` → ``robot_state``."""
    spaced = _CAMEL_BOUNDARY.sub("_", text)
    cleaned = _NOT_IDENTIFIER.sub("_", spaced).strip("_").lower()
    return cleaned or "topic"


def derive_alias(topic: str, taken: set[str]) -> str:
    """A readable, unique alias for a topic.

    The last level is the obvious name; on a collision, earlier levels are
    prepended until the alias is unique, so ``a/temp`` and ``b/temp`` become
    ``temp`` and ``b_temp`` rather than ``temp`` and ``temp_2``.
    """
    levels = [level for level in topic.split("/") if level]
    if not levels:
        levels = [topic]
    for depth in range(1, len(levels) + 1):
        candidate = snake_case("_".join(levels[-depth:]))
        if candidate not in taken:
            return candidate
    candidate = snake_case("_".join(levels))
    suffix = 2
    while f"{candidate}_{suffix}" in taken:
        suffix += 1
    return f"{candidate}_{suffix}"


def infer_definitions(
    observations: dict[str, list[bytes]],
    spec: DiscoverSpec | None = None,
) -> tuple[list[dict], list[str]]:
    """Turn observed payloads into registry entries plus review notes.

    Returns ``(definitions, warnings)``.  Definitions are plain dicts in the
    registry's own shape, ready to be dumped as YAML; warnings name every guess a
    human should check.
    """
    spec = spec or DiscoverSpec()
    definitions: list[dict] = []
    warnings: list[str] = []
    taken: set[str] = set()

    for topic in sorted(observations):
        if any(topic_matches(f, topic) for f in spec.exclude):
            continue
        payloads = observations[topic]
        payload_type, keys = infer_payload_type(payloads)

        alias = spec.aliases.get(topic) or derive_alias(topic, taken)
        taken.add(alias)

        definition: dict[str, Any] = {
            "alias": alias,
            "topic": topic,
            "payload_type": payload_type.value,
        }
        if payload_type is MqttPayloadType.JSON and keys:
            # A json topic almost always wants one field, and naming the ones we
            # saw saves a round trip through mosquitto_sub.
            definition["description"] = f"json keys seen: {', '.join(keys)}"
        definitions.append(definition)

        if len(payloads) == 1:
            warnings.append(
                f"{alias} ({topic}): only 1 sample — payload_type "
                f"'{payload_type.value}' is a guess from a single message"
            )
        if payload_type is MqttPayloadType.INT:
            distinct = {p.strip() for p in (_decode_text(p) or "" for p in payloads)}
            if distinct <= {"0", "1"}:
                warnings.append(
                    f"{alias} ({topic}): only saw 0/1 — typed 'int'; change it to "
                    "'bool' if it is a flag"
                )
        if payload_type is MqttPayloadType.JSON and not keys:
            warnings.append(
                f"{alias} ({topic}): json arrays only — no keys to suggest a "
                "json_path for"
            )

    return definitions, warnings


# ── Sniffing (I/O) ────────────────────────────────────────────────────────────

def sniff(
    spec: DiscoverSpec,
    manager: MqttClientManager | None = None,
    on_message: Any = None,
) -> dict[str, list[bytes]]:
    """Listen for ``spec.duration`` seconds and return topic → payloads.

    Overlapping filters (``a/#`` and ``a/b``) deliver the same message twice; it
    is counted once, so the sample counts in the warnings stay honest.
    """
    manager = manager or MqttClientManager.get_instance()
    manager.connect(DISCOVER_CLIENT_ID, spec.broker)

    subscriptions = []
    observations: dict[str, list[bytes]] = {}
    seen: set[int] = set()
    try:
        for topic_filter in spec.filters:
            subscriptions.append(
                manager.subscribe(DISCOVER_CLIENT_ID, topic_filter, spec.qos)
            )
        logger.info("listening to %s for %.0fs", ", ".join(spec.filters), spec.duration)

        deadline = time.monotonic() + spec.duration
        while time.monotonic() < deadline:
            received = False
            for subscription in subscriptions:
                for message in subscription.drain():
                    received = True
                    if id(message) in seen:
                        continue  # same object, delivered via a second filter
                    seen.add(id(message))
                    observations.setdefault(message.topic, []).append(message.payload)
                    if on_message is not None:
                        on_message(message)
            if not received:
                time.sleep(0.02)
    finally:
        for subscription in subscriptions:
            subscription.close()
        manager.disconnect(DISCOVER_CLIENT_ID)

    logger.info("saw %d topic(s), %d message(s)",
                len(observations), sum(len(v) for v in observations.values()))
    return observations


def discover(
    spec: DiscoverSpec,
    manager: MqttClientManager | None = None,
) -> tuple[list[dict], list[str], dict[str, list[bytes]]]:
    """:func:`sniff` followed by :func:`infer_definitions`."""
    observations = sniff(spec, manager=manager)
    definitions, warnings = infer_definitions(observations, spec)
    return definitions, warnings, observations


# ── Writing the registry ──────────────────────────────────────────────────────

def render(definitions: list[dict], preserved: dict, source: str,
           samples: int, duration: float, manual: list[dict] | None = None) -> str:
    """Render the registry file: generated ``topics:``, hand-written ones, and
    every preserved section.

    ``manual`` entries are appended after the generated ones so a re-discover
    never deletes what a human authored.
    """
    topics = list(definitions) + list(manual or [])
    body = str(yaml.safe_dump({"topics": topics}, sort_keys=False,
                              default_flow_style=False, width=100))
    text = HEADER.format(source=source, samples=samples, duration=duration) + "\n" + body
    if preserved:
        text += "\n" + str(yaml.safe_dump(preserved, sort_keys=False,
                                          default_flow_style=False, width=100))
    return text


def preserved_sections(path: Path) -> dict:
    """Everything in an existing registry that discovery must not touch."""
    if not path.exists():
        return {}
    existing = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {key: value for key, value in existing.items() if key != "topics"}


def manual_topics(path: Path) -> list[dict]:
    """Committed topics marked ``manual: true``.

    Wildcards, request/response pairs and value_maps cannot be sniffed — only a
    human can author them. They are carried across a re-discover unchanged, and
    :func:`drift` ignores them, so ``--check`` stays a real gate instead of
    reporting the same hand-written entries as missing every run.
    """
    if not path.exists():
        return []
    existing = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return [topic for topic in (existing.get("topics") or [])
            if isinstance(topic, dict) and topic.get("manual")]


def _comparable(definition: dict) -> tuple[str, str]:
    """The part of an entry a sniff can actually determine: topic and type.

    Everything else in a registry entry — qos, json_path, retain, value_map,
    description — is a human's decision that discovery knows nothing about, so
    comparing it would make every reviewed file look like drift.
    """
    return str(definition.get("topic", "")), str(definition.get("payload_type", ""))


def drift(path: Path, definitions: list[dict]) -> list[str]:
    """Describe how a committed registry differs from a fresh sniff.

    Empty list means they agree.  Used by ``discover --check`` as a CI gate, and
    it only reports what discovery can see: a topic that appeared, a topic that
    did not publish at all, or an observed payload type that contradicts the
    committed one.  Entries marked ``manual: true`` are skipped entirely.

    Unlike ``bteng-opcua harvest --check``, a red result here is not proof of a
    stale file: a topic that simply stayed quiet during the window looks exactly
    like a removal.  It means "look at this", not "you are wrong".
    """
    if not path.exists():
        return [f"{path} does not exist"]
    current = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    committed = [topic for topic in (current.get("topics") or [])
                 if not (isinstance(topic, dict) and topic.get("manual"))]

    by_alias_old = {str(d.get("alias")): d for d in committed}
    by_alias_new = {str(d.get("alias")): d for d in definitions}
    if {a: _comparable(d) for a, d in by_alias_old.items()} == \
       {a: _comparable(d) for a, d in by_alias_new.items()}:
        return []

    report: list[str] = []
    for alias in sorted(set(by_alias_new) - set(by_alias_old)):
        report.append(f"+ {alias}: {by_alias_new[alias].get('topic')} "
                      f"({by_alias_new[alias].get('payload_type')}) — seen but not in the file")
    for alias in sorted(set(by_alias_old) - set(by_alias_new)):
        report.append(f"- {alias}: {by_alias_old[alias].get('topic')} "
                      "— in the file but nothing published during the window")
    for alias in sorted(set(by_alias_old) & set(by_alias_new)):
        old, new = _comparable(by_alias_old[alias]), _comparable(by_alias_new[alias])
        if old != new:
            report.append(f"~ {alias}: {old[0]} is {old[1]} in the file, "
                          f"but {new[0]} published {new[1]}")
    return report


def wildcard_aliases(definitions: list[dict]) -> list[str]:
    """Aliases whose topic is a filter — never generated, but a hand-edit might."""
    return [d["alias"] for d in definitions if is_wildcard(str(d.get("topic", "")))]
